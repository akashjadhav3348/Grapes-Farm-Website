import { test, expect } from '@playwright/test';
async function login(page) {
  await page.goto('/login');
  await page.getByLabel('Email address').fill('test@example.com');
  await page.getByLabel('Password', {exact:true}).fill('Browser-test-only-2026');
  await page.getByRole('button',{name:'Sign in securely'}).click();
  await expect(page.locator('#dashboard')).toBeVisible();
}
async function add(page,name,gender='unknown') {
  await page.getByRole('button',{name:'+ Add Member',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Full name',{exact:true}).fill(name);
  await dialog.getByLabel('Gender for family wording').selectOption(gender);
  await dialog.getByRole('button',{name:'Save member',exact:true}).click();
  await expect(dialog).not.toBeVisible();
}
test('desktop acceptance: sign in, parents, duplicate names, details, persistent links',async({page})=>{
  await login(page);
  await page.goto('/admin/family-tree');
  await add(page,'Suresh Jadhav','male');
  await expect(page.locator('.swal2-container.swal2-top-end')).toContainText('Family member added');
  await add(page,'Sunita Jadhav','female');
  await page.getByLabel('Search family').fill('Suresh Jadhav');
  await page.locator('.family-search-results button').click();
  const sureshCard=page.locator('.family-tree-card').filter({hasText:'Suresh Jadhav'});
  await sureshCard.getByRole('button',{name:'Add Child',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await expect(dialog.getByRole('heading',{name:'Add child to Suresh Jadhav'})).toBeVisible();
  const father=dialog.getByLabel('Father',{exact:true});
  await expect(father.locator('option:checked')).toContainText('Suresh Jadhav');
  await expect(dialog.getByLabel('Mother',{exact:true})).toHaveValue('');
  await dialog.getByLabel('Full name',{exact:true}).fill('Rohan Jadhav');
  await dialog.getByLabel('Gender for family wording').selectOption('male');
  await dialog.getByLabel('Mother search').fill('Sunita');
  const mother=dialog.getByLabel('Mother',{exact:true});
  await mother.selectOption(await mother.locator('option').filter({hasText:'Sunita'}).getAttribute('value'));
  await expect(dialog.locator('.family-preview')).toContainText('Rohan Jadhav is the son of Suresh Jadhav and Sunita Jadhav.');
  await dialog.getByRole('button',{name:'Save member',exact:true}).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  await page.getByLabel('Search family').fill('Rohan');
  await page.locator('.family-search-results button').click();
  await page.getByRole('button',{name:'View details for Rohan Jadhav',exact:true}).click();
  await expect(page.locator('.family-detail-relations')).toContainText('Suresh Jadhav');
  await expect(page.locator('.family-detail-relations')).toContainText('Sunita Jadhav');
  await page.goto('/admin/family-tree');
  await add(page,'Unknown Parents Person');
  await page.getByLabel('Search family').fill('Unknown Parents');
  await page.locator('.family-search-results button').click();
  await page.getByRole('button',{name:'View details for Unknown Parents Person'}).click();
  await page.getByRole('button',{name:'Edit parents',exact:true}).click();
  await page.locator('.family-member-details').getByLabel('Father search').fill('Suresh');
  const select=page.locator('.family-member-details').getByLabel('Father',{exact:true});
  await select.selectOption(await select.locator('option').filter({hasText:'Suresh'}).getAttribute('value'));
  await page.getByRole('button',{name:'Save parent links'}).click();
  await expect(page.locator('.family-detail-relations')).toContainText('Suresh');
  await page.goto('/admin/family-tree');
  await add(page,'Rohan Jadhav');
  await page.getByLabel('Search family').fill('Rohan');
  await expect(page.locator('.family-search-results button')).toHaveCount(2);
  const labels=await page.locator('.family-search-results small').allTextContents();
  expect(labels[0]).not.toBe(labels[1]);
});
test('mobile list, sidebar, protected routes',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await login(page);
  await page.goto('/admin/family-tree');
  await expect(page.locator('.family-list-view')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Sections',exact:true}).click();
  await expect(page.locator('#admin-sections')).toBeVisible();
  await page.getByRole('button',{name:'Members',exact:true}).click();
  await expect(page.locator('.family-members-table')).toBeVisible();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await expect(page).toHaveURL(/\/login$/);
  await expect(page.getByRole('heading',{name:'Admin sign in'})).toBeVisible();
  await page.goto('/admin/members');
  await expect(page.getByRole('heading',{name:'Admin sign in'})).toBeVisible();
  expect((await page.request.get('/api/admin/family')).status()).toBe(401);
});
test('login route always shows form and sidebar labels have contrast',async({page})=>{
 await login(page);
 const styles=await page.locator('#admin-sections button[aria-pressed="false"]').first().evaluate(el=>({color:getComputedStyle(el).color,background:getComputedStyle(el).backgroundColor}));
 expect(styles.color).toBe('rgb(255, 255, 255)');
 expect(styles.background).toBe('rgba(0, 0, 0, 0)');
 await page.goto('/login');
 await expect(page.getByRole('heading',{name:'Admin sign in'})).toBeVisible();
 await expect(page.locator('#dashboard')).toHaveCount(0);
 await login(page);
 await expect(page).toHaveURL(/\/admin$/);
 await page.reload();
 await expect(page.locator('#dashboard')).toBeVisible();
});
